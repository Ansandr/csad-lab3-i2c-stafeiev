--------------------------------------------------------------------------------
-- i2c_master_tx.vhd
-- I2C master TRANSMITTER (write transaction), VHDL-2008, synthesizable.
--   ADCS lab "Serial protocols on FPGA", variant 23: I2C + VHDL.
--   Author: Stafeiev Andrii (KI-407).
--
-- One transaction:  START | ADDR[6:0] + W(0) | ACK | DATA[7:0] | ACK | STOP
--
-- Bus electrical model: SCL and SDA are OPEN-DRAIN. The module never drives
-- '1': it either pulls the line to '0' or releases it ('Z'); an external
-- pull-up (in simulation: the weak value 'H') makes the line high.
--
-- Timing: every SCL period is split into 4 quarter phases generated by a
-- clock divider (QUARTER = CLK_FREQ_HZ / (4 * I2C_FREQ_HZ) system clocks):
--   phase 0 : SCL low   -> put the next bit on SDA (SDA changes only while SCL low)
--   phase 1 : release SCL (goes high through the pull-up)
--   phase 2 : SCL high  -> sample SDA (ACK bit); wait here if a slave stretches SCL
--   phase 3 : pull SCL low
--------------------------------------------------------------------------------
library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity i2c_master_tx is
  generic (
    CLK_FREQ_HZ : positive := 50_000_000;  -- system clock frequency
    I2C_FREQ_HZ : positive := 100_000      -- SCL frequency (standard mode 100 kHz)
  );
  port (
    clk       : in    std_logic;                     -- system clock
    rst       : in    std_logic;                     -- synchronous reset, active high
    start     : in    std_logic;                     -- 1-clk pulse: begin a write transaction
    addr      : in    std_logic_vector(6 downto 0);  -- 7-bit slave address
    data_in   : in    std_logic_vector(7 downto 0);  -- byte to transmit
    busy      : out   std_logic;                     -- '1' while a transaction is running
    done      : out   std_logic;                     -- 1-clk pulse at the end of STOP
    ack_error : out   std_logic;                     -- '1' if the slave answered NACK (valid with done)
    scl       : inout std_logic;                     -- I2C clock line (open drain)
    sda       : inout std_logic                      -- I2C data line  (open drain)
  );
end entity;

architecture rtl of i2c_master_tx is
  constant QUARTER : positive := CLK_FREQ_HZ / (4 * I2C_FREQ_HZ);

  -- Transmitter FSM states (see the state diagram in the report)
  type state_t is (S_IDLE, S_START, S_SEND_BIT, S_ACK, S_STOP);
  signal state     : state_t := S_IDLE;

  signal div_cnt   : natural range 0 to QUARTER - 1 := 0;  -- clock divider counter
  signal tick      : std_logic := '0';                    -- one clk pulse per quarter of SCL
  signal phase     : natural range 0 to 3 := 0;           -- quarter phase inside one SCL bit
  signal bit_cnt   : natural range 0 to 7 := 7;           -- index of the bit being sent
  signal shreg     : std_logic_vector(7 downto 0) := (others => '0');  -- transmit shift register
  signal data_reg  : std_logic_vector(7 downto 0) := (others => '0');  -- latched data byte
  signal byte_no   : natural range 0 to 1 := 0;           -- 0 = address byte, 1 = data byte
  signal nack_seen : std_logic := '0';                    -- remembers a NACK

  signal scl_oe    : std_logic := '0';  -- '1' = pull SCL low, '0' = release
  signal sda_oe    : std_logic := '0';  -- '1' = pull SDA low, '0' = release
begin
  -- Open-drain output buffers
  scl <= '0' when scl_oe = '1' else 'Z';
  sda <= '0' when sda_oe = '1' else 'Z';

  busy <= '0' when state = S_IDLE else '1';

  ------------------------------------------------------------------------------
  -- Clock divider: produces 'tick' 4 times per SCL period.
  ------------------------------------------------------------------------------
  divider : process (clk)
  begin
    if rising_edge(clk) then
      tick <= '0';
      if rst = '1' or state = S_IDLE then
        div_cnt <= 0;
      elsif div_cnt = QUARTER - 1 then
        div_cnt <= 0;
        tick    <= '1';
      else
        div_cnt <= div_cnt + 1;
      end if;
    end if;
  end process;

  ------------------------------------------------------------------------------
  -- Transmitter FSM
  ------------------------------------------------------------------------------
  fsm : process (clk)
    -- clock stretching: SCL released by us but held low by a slave
    variable stretched : boolean;
  begin
    if rising_edge(clk) then
      done <= '0';
      if rst = '1' then
        state     <= S_IDLE;
        scl_oe    <= '0';
        sda_oe    <= '0';
        phase     <= 0;
        ack_error <= '0';
        nack_seen <= '0';
      else
        stretched := (scl_oe = '0') and (to_x01(scl) = '0') and (state /= S_IDLE);
        case state is
          when S_IDLE =>
            scl_oe <= '0';
            sda_oe <= '0';
            if start = '1' then
              shreg     <= addr & '0';           -- R/W = 0 : write
              data_reg  <= data_in;
              byte_no   <= 0;
              bit_cnt   <= 7;
              phase     <= 0;
              nack_seen <= '0';
              ack_error <= '0';
              state     <= S_START;
            end if;

          when others =>
            if tick = '1' and not stretched then
              phase <= (phase + 1) mod 4;
              case state is
                -- START: SDA 1->0 while SCL is high, then SCL low
                when S_START =>
                  case phase is
                    when 0 => sda_oe <= '0'; scl_oe <= '0';
                    when 1 => sda_oe <= '1';             -- START condition
                    when 2 => null;
                    when 3 => scl_oe <= '1'; state <= S_SEND_BIT;
                  end case;

                -- 8 bits, MSB first
                when S_SEND_BIT =>
                  case phase is
                    when 0 => sda_oe <= not shreg(7);    -- '0' -> pull low, '1' -> release
                    when 1 => scl_oe <= '0';
                    when 2 => null;
                    when 3 =>
                      scl_oe <= '1';
                      shreg  <= shreg(6 downto 0) & '0';
                      if bit_cnt = 0 then
                        state <= S_ACK;
                      else
                        bit_cnt <= bit_cnt - 1;
                      end if;
                  end case;

                -- 9th clock: release SDA, slave pulls it low for ACK
                when S_ACK =>
                  case phase is
                    when 0 => sda_oe <= '0';
                    when 1 => scl_oe <= '0';
                    when 2 =>
                      if to_x01(sda) /= '0' then
                        nack_seen <= '1';
                      end if;
                    when 3 =>
                      scl_oe <= '1';
                      if nack_seen = '1' or byte_no = 1 then
                        state <= S_STOP;
                      else
                        byte_no <= 1;
                        shreg   <= data_reg;
                        bit_cnt <= 7;
                        state   <= S_SEND_BIT;
                      end if;
                  end case;

                -- STOP: SDA 0->1 while SCL is high
                when S_STOP =>
                  case phase is
                    when 0 => sda_oe <= '1';
                    when 1 => scl_oe <= '0';
                    when 2 => sda_oe <= '0';             -- STOP condition
                    when 3 =>
                      done      <= '1';
                      ack_error <= nack_seen;
                      state     <= S_IDLE;
                  end case;

                when S_IDLE => null;
              end case;
            end if;
        end case;
      end if;
    end if;
  end process;
end architecture;
